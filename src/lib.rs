//! Types and dispatch for exchanging values between two independently built
//! Rust binaries.
//!
//! Rust's own ABI is deliberately unspecified: field order, enum
//! discriminants, `Option` niches and trait-object vtables may all change
//! between compiler versions, and a `Box` allocated in one dynamic library may
//! not be releasable in another. This crate replaces each of those with an
//! explicit, `#[repr(C)]` shape and moves the ownership rule into the value
//! itself.
//!
//! # The rules the crate keeps
//!
//! - Every boundary type is `#[repr(C)]` and stores widths explicitly: lengths
//!   and capacities are `u64`, tags are `u32`, and `usize` never appears in a
//!   shared struct. Widths are fixed, but the types still hold pointers, so a
//!   32-bit and a 64-bit build cannot exchange them: the guarantee is the same
//!   layout across revisions of a build with the same target.
//! - Optional and fallible values carry an explicit tag instead of a niche, so
//!   `size_of::<StableOption<T>>()` does not depend on which niches `T` has.
//! - Every owned allocation carries an [`AbiAllocator`]; dropping the value on
//!   either side releases the block through the functions that produced it.
//! - Trait objects use a table generated by [`stable_object!`]. The table starts
//!   with a [`VTablePrefix`], which records the type identifier, a signature
//!   derived from the method list, the boundary layout revision, the size and
//!   alignment of the value, the number of slots that follow, and the function
//!   that releases the value; each slot after it pairs the identifier of one
//!   method with the address of its trampoline. [`stable_object!`] checks the
//!   signature when a handle is adopted from another build.
//! - Two sides agree on an [`AbiVersion`] before exchanging anything, and the
//!   entry protocol validates how many bytes the other side wrote.
//!
//! # What the crate does not do for you
//!
//! A value that arrives as raw bytes is still the receiver's responsibility to
//! validate before it is interpreted as one of these types: `mem::transmute`
//! and `ptr::read` are `unsafe` for exactly that reason. The constructors that
//! check the parts of a value are [`StableStr::from_raw_parts_checked`],
//! [`StableSlice::from_raw_parts_checked`],
//! [`StableSliceMut::from_raw_parts_checked`],
//! [`StableBox::from_raw_parts_checked`], the `from_raw_parts` of the owned
//! containers, and the checked adoption in [`stable_object!`]. A value that arrives already built is checked with
//! [`AbiType::validate`], which the generated accessors call on every return
//! value.
//!
//! A value that owns storage is deliberately not `Send` or `Sync`: its
//! allocator was handed over by one side and nothing proves it accepts calls
//! from another thread. That covers [`StableString`], [`StableVec`],
//! [`StableBox`], the maps and sets, and the handles a declaration generates.
//! The values that own no storage - the borrowed views, [`StableArray`], the
//! tuples, [`StableDuration`], [`AbiVersion`], [`Handle`] and the time values -
//! carry nothing but their parts, so the compiler gives them `Send` and `Sync`
//! when their parts have them. The copy-on-write values are the exception to
//! that reading: both of their fields are present whatever the tag says, and the
//! inactive one carries an allocator, so [`StableCowStr::borrowed`] and
//! [`StableCowSlice::borrowed`] are not `Send` either. A holder that knows its
//! allocator is thread safe can state that guarantee for an owning value in a
//! wrapper of its own.
//!
//! # Example
//!
//! ```
//! use xt_stable_abi::{stable_object, StableStr};
//!
//! stable_object! {
//!     /// A handle to a word counter.
//!     pub struct CounterObject;
//!     /// The table behind [`CounterObject`].
//!     pub struct CounterVTable;
//!     /// Counts words in a line.
//!     pub trait Counter {
//!         /// Counts the words in `line`.
//!         fn count(&self, line: StableStr) -> u32;
//!         /// Resets the running total.
//!         fn reset(&mut self);
//!     }
//! }
//!
//! struct Words {
//!     total: u32,
//! }
//!
//! impl Counter for Words {
//!     fn count(&self, line: StableStr<'_>) -> u32 {
//!         self.total + line.as_str().split_whitespace().count() as u32
//!     }
//!
//!     fn reset(&mut self) {
//!         self.total = 0;
//!     }
//! }
//!
//! fn main() {
//!     let mut object = CounterObject::abi_from_value(Words { total: 0 });
//!     let count = unsafe { object.count(StableStr::from_str("one two three")) };
//!     assert_eq!(count, 3);
//!     unsafe { object.reset() };
//!     assert!(!object.abi_is_empty());
//! }
//! ```
//!
//! # Panics
//!
//! Generated accessors call through `extern "C"` function pointers, and a panic
//! that unwinds out of an `extern "C"` function aborts the process. Declaring
//! the object with [`stable_object_guarded!`] instead of [`stable_object!`]
//! catches the panic inside the trampoline and reports it as
//! [`AbiStatus::Panic`]; a boundary function written by hand can wrap its body
//! in [`unwind::guarded`] for the same effect.

