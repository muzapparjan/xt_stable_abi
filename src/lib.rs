// A type made of plain data has one surface in both builds: a value of it
// crosses the boundary the same way whether or not the `std` feature is on, so a
// constructor that exists in only one build is a gap the other cannot work
// around. This closure is never called; it makes a `no_std` build type-check the
// constructors a caller of `StableDuration` uses.
#[cfg(not(feature = "std"))]
const _: fn() = || {
    let mut span = StableDuration::from_secs(1);
    span = StableDuration::from_millis(1_500).unwrap_or(span);
    span = StableDuration::from_micros(1_500_000).unwrap_or(span);
    span = StableDuration::from_nanos(1_500_000_000).unwrap_or(span);
    let _ = span.as_secs_f64();
    if let Some(third) = span.checked_div(3) {
        span = third;
    }
    let _ = span;
};

